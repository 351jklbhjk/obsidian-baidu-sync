var MAGIC_HEADER = new Uint8Array([66, 68, 83, 89, 78, 67, 95, 69, 50, 69, 69, 1]);
var PBKDF2_ITERATIONS = 6e5;
var LEGACY_PBKDF2_ITERATIONS = 1e5;
function isEncrypted(buffer) {
  if (buffer.byteLength < MAGIC_HEADER.length + 16 + 12 + 16) {
    return false;
  }
  const view = new Uint8Array(buffer, 0, MAGIC_HEADER.length);
  for (let i = 0; i < MAGIC_HEADER.length; i++) {
    if (view[i] !== MAGIC_HEADER[i]) {
      return false;
    }
  }
  return true;
}
function getCrypto() {
  if (typeof activeWindow !== "undefined" && activeWindow.crypto) {
    return activeWindow.crypto;
  }
  if (typeof window !== "undefined" && window.crypto) {
    return window.crypto;
  }
  return crypto;
}
async function deriveKey(password, salt, iterations = PBKDF2_ITERATIONS) {
  const enc = new TextEncoder();
  const crypto2 = getCrypto();
  const keyMaterial = await crypto2.subtle.importKey(
    "raw",
    enc.encode(password),
    { name: "PBKDF2" },
    false,
    ["deriveKey"]
  );
  return crypto2.subtle.deriveKey(
    {
      name: "PBKDF2",
      salt,
      iterations,
      hash: "SHA-256"
    },
    keyMaterial,
    { name: "AES-GCM", length: 256 },
    false,
    ["encrypt", "decrypt"]
  );
}
async function encryptData(data, password) {
  const crypto2 = getCrypto();
  const salt = crypto2.getRandomValues(new Uint8Array(16));
  const iv = crypto2.getRandomValues(new Uint8Array(12));
  const key = await deriveKey(password, salt);
  const ciphertext = await crypto2.subtle.encrypt(
    {
      name: "AES-GCM",
      iv
    },
    key,
    data
  );
  const totalLength = MAGIC_HEADER.length + salt.length + iv.length + ciphertext.byteLength;
  const result = new Uint8Array(totalLength);
  let offset = 0;
  result.set(MAGIC_HEADER, offset);
  offset += MAGIC_HEADER.length;
  result.set(salt, offset);
  offset += salt.length;
  result.set(iv, offset);
  offset += iv.length;
  result.set(new Uint8Array(ciphertext), offset);
  return result.buffer;
}
async function decryptData(encryptedBuffer, password) {
  if (!isEncrypted(encryptedBuffer)) {
    return encryptedBuffer;
  }
  let offset = MAGIC_HEADER.length;
  const salt = new Uint8Array(encryptedBuffer, offset, 16);
  offset += 16;
  const iv = new Uint8Array(encryptedBuffer, offset, 12);
  offset += 12;
  const ciphertext = encryptedBuffer.slice(offset);
  const crypto2 = getCrypto();
  try {
    const key = await deriveKey(password, salt, PBKDF2_ITERATIONS);
    return await crypto2.subtle.decrypt(
      {
        name: "AES-GCM",
        iv
      },
      key,
      ciphertext
    );
  } catch {
    try {
      const legacyKey = await deriveKey(password, salt, LEGACY_PBKDF2_ITERATIONS);
      return await crypto2.subtle.decrypt(
        {
          name: "AES-GCM",
          iv
        },
        legacyKey,
        ciphertext
      );
    } catch {
      throw new Error("E2EE \u89E3\u5BC6\u5931\u8D25\uFF1A\u5BC6\u7801\u9519\u8BEF\u6216\u6587\u4EF6\u635F\u574F");
    }
  }
}

