function globToRegex(glob) {
  const clean = glob.trim();
  let regexStr = "^";
  let i = 0;
  while (i < clean.length) {
    const c = clean[i];
    if (c === "*" && clean[i + 1] === "*") {
      regexStr += ".*";
      i += 2;
      if (clean[i] === "/") {
        i++;
      }
    } else if (c === "*") {
      regexStr += "[^/]*";
      i++;
    } else if (c === "?") {
      regexStr += "[^/]";
      i++;
    } else if (".+^$()|{}[]\\".includes(c)) {
      regexStr += "\\" + c;
      i++;
    } else {
      regexStr += c;
      i++;
    }
  }
  regexStr += "$";
  return new RegExp(regexStr);
}
var SyncFilter = class {
  constructor(settings, configDir = "") {
    this.settings = settings;
    this.configDir = configDir;
    this.compiledPatterns = [];
    this.recompilePatterns();
  }
  updateSettings(settings) {
    this.settings = settings;
    this.recompilePatterns();
  }
  recompilePatterns() {
    this.compiledPatterns = [];
    const lines = this.settings.ignoredPatterns.split("\n");
    for (const line of lines) {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith("#")) {
        try {
          this.compiledPatterns.push(globToRegex(trimmed));
        } catch {
        }
      }
    }
  }
  shouldIgnore(relativePath) {
    const normalized = relativePath.replace(/\\/g, "/");
    if (normalized === ".baidu-sync-index.json") return true;
    if (normalized.includes("baidu-netdisk-sync") || normalized.includes("obsidian-baidu-netdisk-sync") || normalized.endsWith("sync_manifest.json")) {
      return true;
    }
    if (normalized.startsWith(".trash/") || normalized === ".trash") {
      return true;
    }
    if (normalized.startsWith(".git/") || normalized.includes("/.git/")) {
      return true;
    }
    const configPrefix = this.configDir ? `${this.configDir}/` : "";
    if (configPrefix && normalized.startsWith(configPrefix)) {
      if (!this.settings.syncObsidianConfig) {
        return true;
      }
      if (normalized.includes("/workspace.json") || normalized.includes("/workspace-mobile.json") || normalized.endsWith("/workspace.json") || normalized.endsWith("/workspace-mobile.json") || normalized.includes("/cache/") || normalized.includes("/indexeddb/")) {
        return true;
      }
      if (!this.settings.syncPlugins && normalized.includes("/plugins/")) {
        return true;
      }
      if (!this.settings.syncThemes && normalized.includes("/themes/")) {
        return true;
      }
    }
    for (const pattern of this.compiledPatterns) {
      if (pattern.test(normalized)) {
        return true;
      }
    }
    return false;
  }
};

